"""Curated public dataset registry for space + mechanical CAD training."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Any


@dataclass(frozen=True, slots=True)
class DatasetSource:
    key: str
    title: str
    domain: str
    url: str
    license: str
    use_cases: tuple[str, ...]
    notes: str = ""
    size_hint: str = ""
    recommended_for: tuple[str, ...] = ()
    information_mode: str = ""

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _normalise_text(*parts: str) -> str:
    return " ".join(part for part in parts if part).lower()


def infer_information_mode(source: DatasetSource) -> str:
    text = _normalise_text(source.key, source.title, source.domain, source.url, source.license, source.notes, source.size_hint, " ".join(source.use_cases), " ".join(source.recommended_for))
    if any(hint in text for hint in ("marketplace", "private reference", "reference-only", "user uploads", "third-party", "sketchfab", "grabcad", "printables", "makerworld")):
        return "reference-only-geometry"
    if any(hint in text for hint in ("toolkit", "export toolkit", "software", "package", "generator")):
        return "toolkit"
    if any(hint in text for hint in ("shape model", "shape models", "mesh surfaces", "asteroid", "comet")):
        return "mesh-shape"
    if any(hint in text for hint in ("dataset", "database", "catalog", "archive", "registry", "holdings", "repository")):
        return "database-catalog"
    if any(hint in text for hint in ("schematic", "blueprint", "exploded view", "drawing", "diagram", "cutaway")):
        return "diagram-blueprint"
    if any(hint in text for hint in ("report", "paper", "thesis", "study", "review", "analysis", "roadmap", "brochure", "pdf", "design of")):
        return "technical-report"
    if any(hint in text for hint in ("3d model", "3d models", "interactive 3d model", "step", "stl", "iges", "cad", "parts database", "parts library", "geometry", "print model", "print models", "reference model", "spacecraft geometry", "rocket parts", "visual priors")):
        return "cad-model"
    return "technical-report"


def _ds(
    key: str,
    title: str,
    domain: str,
    url: str,
    license: str,
    use_cases: tuple[str, ...],
    notes: str = "",
    size_hint: str = "",
    recommended_for: tuple[str, ...] = (),
    information_mode: str | None = None,
) -> DatasetSource:
    source = DatasetSource(
        key=key,
        title=title,
        domain=domain,
        url=url,
        license=license,
        use_cases=use_cases,
        notes=notes,
        size_hint=size_hint,
        recommended_for=recommended_for,
        information_mode=information_mode or "",
    )
    if source.information_mode:
        return source
    return DatasetSource(
        key=key,
        title=title,
        domain=domain,
        url=url,
        license=license,
        use_cases=use_cases,
        notes=notes,
        size_hint=size_hint,
        recommended_for=recommended_for,
        information_mode=infer_information_mode(source),
    )


